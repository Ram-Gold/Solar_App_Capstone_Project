-- Inquiry Rate Limiting: 3 combined Inquiries per rolling 60-minute window
CREATE TABLE IF NOT EXISTS public.inquiry_rate_limits (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rate_key text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_inquiry_rate_limits_key_created
  ON public.inquiry_rate_limits (rate_key, created_at DESC);

ALTER TABLE public.inquiry_rate_limits ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.enforce_inquiry_rate_limit()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_is_privileged boolean := false;
  v_headers jsonb;
  v_forwarded text;
  v_ip text;
  v_rate_key text;
  v_count integer;
  v_oldest_at timestamptz;
  v_wait_minutes integer;
BEGIN
  -- Exempt authenticated staff and admin operators
  IF auth.uid() IS NOT NULL THEN
    SELECT EXISTS (
      SELECT 1
      FROM public.user_profiles
      WHERE id = auth.uid()
        AND role IN ('staff', 'admin')
    ) INTO v_is_privileged;

    IF v_is_privileged THEN
      RETURN NEW;
    END IF;
  END IF;

  -- Extract client IP from PostgREST request.headers, falling back to auth.uid()
  BEGIN
    v_headers := NULLIF(current_setting('request.headers', true), '')::jsonb;
  EXCEPTION WHEN OTHERS THEN
    v_headers := NULL;
  END;

  IF v_headers IS NOT NULL THEN
    v_ip := NULLIF(trim(v_headers ->> 'cf-connecting-ip'), '');
    IF v_ip IS NULL THEN
      v_forwarded := NULLIF(trim(v_headers ->> 'x-forwarded-for'), '');
      IF v_forwarded IS NOT NULL THEN
        v_ip := NULLIF(trim(split_part(v_forwarded, ',', 1)), '');
      END IF;
    END IF;
    IF v_ip IS NULL THEN
      v_ip := NULLIF(trim(v_headers ->> 'x-real-ip'), '');
    END IF;
  END IF;

  v_rate_key := COALESCE(
    CASE WHEN v_ip IS NOT NULL THEN 'ip:' || v_ip END,
    CASE WHEN auth.uid() IS NOT NULL THEN 'uid:' || auth.uid()::text END,
    'anon:unknown'
  );

  -- Check rolling 60-minute window
  SELECT count(*), min(created_at)
  INTO v_count, v_oldest_at
  FROM public.inquiry_rate_limits
  WHERE rate_key = v_rate_key
    AND created_at > now() - interval '60 minutes';

  IF v_count >= 3 THEN
    v_wait_minutes := GREATEST(
      1,
      CEIL(EXTRACT(EPOCH FROM ((v_oldest_at + interval '60 minutes') - now())) / 60.0)::integer
    );
    RAISE EXCEPTION 'RATE_LIMIT_EXCEEDED: Limit of 3 inquiries per hour reached. Try again in % minute(s).', v_wait_minutes
      USING ERRCODE = 'P0001';
  END IF;

  INSERT INTO public.inquiry_rate_limits (rate_key)
  VALUES (v_rate_key);

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_enforce_inquiry_rate_limit ON public.quote_tickets;
CREATE TRIGGER trg_enforce_inquiry_rate_limit
  BEFORE INSERT ON public.quote_tickets
  FOR EACH ROW
  EXECUTE FUNCTION public.enforce_inquiry_rate_limit();
